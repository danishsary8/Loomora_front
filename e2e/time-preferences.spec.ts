import AxeBuilder from '@axe-core/playwright'
import { expect, test } from '@playwright/test'

test.use({ timezoneId: 'Asia/Phnom_Penh', reducedMotion: 'reduce' })

test('guest clock format and first weekday apply across pages and reload', async ({
  page,
}, info) => {
  test.skip(info.project.name !== 'phone-375', 'Mobile viewport scenario')
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('console', (message) => {
    if (message.type() === 'error') errors.push(message.text())
  })
  await page.goto('/profile')
  const timeFormat = page.getByRole('combobox', { name: 'Time format' })
  const weekStart = page.getByRole('combobox', { name: 'Week starts on' })
  const strip = page.getByRole('group', { name: 'Days of the week' })
  const weekday = (name: string) => strip.getByRole('button', { name, exact: true })
  await expect(timeFormat).toHaveValue('24h')
  await expect(weekStart).toHaveValue('1')

  await page.getByRole('link', { name: 'Week', exact: true }).click()
  await page.getByRole('button', { name: 'Add to my schedule' }).click()
  const sheet = page.getByRole('dialog')
  await sheet.getByLabel('Title').fill('Afternoon study')
  await sheet.getByLabel('Starts', { exact: true }).fill('14:30')
  await sheet.getByLabel('Ends', { exact: true }).fill('15:30')
  await sheet.getByRole('button', { name: 'Sunday', exact: true }).click()
  await sheet.getByRole('button', { name: 'Add', exact: true }).click()
  await expect(sheet).toBeHidden()
  await weekday('Sunday').click()
  await expect(page.getByText('14:30 to 15:30')).toBeVisible()
  await expect(strip.getByRole('button').first()).toHaveAccessibleName('Monday')

  await page.getByRole('link', { name: 'Profile', exact: true }).click()
  await timeFormat.focus()
  await page.keyboard.press('ArrowUp')
  await expect(timeFormat).toHaveValue('12h')
  await page.keyboard.press('Tab')
  await expect(weekStart).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(weekStart).toHaveValue('7')
  await page.keyboard.press('Tab')
  const save = page.getByRole('button', { name: 'Save settings' })
  await expect(save).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByText('Saved.', { exact: true })).toBeVisible()

  const { violations } = await new AxeBuilder({ page })
    .withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa'])
    .analyze()
  expect(violations).toEqual([])
  const width = () => page.evaluate(() => document.documentElement.scrollWidth)
  expect(await width()).toBe(375)
  await page.getByRole('link', { name: 'Week', exact: true }).click()
  await expect(strip.getByRole('button').first()).toHaveAccessibleName('Sunday')
  await weekday('Sunday').press('Enter')
  await expect(page.getByText('2:30 PM to 3:30 PM')).toBeVisible()
  expect(await width()).toBe(375)
  await page.getByRole('button', { name: 'Edit Afternoon study, 2:30 PM to 3:30 PM' }).click()
  await expect(sheet.getByLabel('Starts', { exact: true })).toHaveValue('2:30 PM')
  await expect(sheet.getByLabel('Ends', { exact: true })).toHaveValue('3:30 PM')
  await sheet.getByLabel('Starts', { exact: true }).fill('2:45 pm')
  await sheet.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(sheet).toBeHidden()
  await expect(page.getByText('2:45 PM to 3:30 PM')).toBeVisible()

  await page.getByRole('link', { name: 'Profile', exact: true }).click()
  await page.reload()
  await expect(timeFormat).toHaveValue('12h')
  await expect(weekStart).toHaveValue('7')

  await page.getByRole('link', { name: 'Week', exact: true }).click()
  await expect(strip.getByRole('button').first()).toHaveAccessibleName('Sunday')
  await weekday('Sunday').press('Enter')
  await expect(page.getByText('2:45 PM to 3:30 PM')).toBeVisible()
  expect(await width()).toBe(375)
  expect(errors).toEqual([])
})
